#!/usr/bin/env python3
"""List the XML element and attribute names each FilmCraft .prproj importer reads.

Reads the importers' non-test source at the pinned commits in IMPORTERS from a local
storytold/filmcraft checkout that has those commits (for example after
`git fetch origin pull/N/head:refs/remotes/prs/N`). Names are taken from string literals that
look like XML names (capitalised, or dotted like `MZ.TrackName`), so the list can include a few
non-XML strings; it is an index for docs/format/, not a parser.

Usage:
    python inventory.py FILMCRAFT_CHECKOUT > ../../docs/format/importer-names.md

MIT OR Apache-2.0.
"""

from __future__ import annotations

import collections
import re
import subprocess
import sys

# PR -> (pinned commit, importer source files). #2296 builds on #1694; #4504 on #2312.
IMPORTERS = {
    "1694": ("ec7df02c4a293a4328870d77e635f6b23a578cb0", ["crates/interchange/src/prproj.rs"]),
    "2296": ("404a7b0becff1623dd86e9178a937d7d7d1cb825", ["crates/interchange/src/prproj.rs"]),
    "3428": ("ee16ebdf678917772c6341d1a4f80541245b1ef7", ["crates/interchange/src/prproj.rs"]),
    "4504": ("b48392fa59f26193c66ba4237e40f4a080cdc769", [
        "crates/interchange/src/premiere.rs",
        "crates/interchange/src/premiere_audio.rs",
        "crates/interchange/src/premiere_color.rs",
        "crates/interchange/src/premiere_items.rs",
        "crates/interchange/src/premiere_markers.rs",
        "crates/interchange/src/premiere_motion.rs",
        "crates/interchange/src/premiere_xml.rs",
    ]),
}

LITERAL = re.compile(r'b?"([A-Za-z][A-Za-z0-9_.:]{1,60})"')


def source(repo: str, commit: str, path: str) -> str:
    out = subprocess.run(["git", "-C", repo, "show", f"{commit}:{path}"], capture_output=True, text=True, encoding="utf-8")
    if out.returncode != 0:
        raise SystemExit(f"cannot read {path} at {commit[:12]}: {out.stderr.strip()}")
    # Test modules hold fixtures, not what the importer reads.
    return re.split(r"#\[cfg\(test\)\]\s*mod tests", out.stdout)[0]


def main() -> int:
    if len(sys.argv) != 2:
        print("usage: inventory.py FILMCRAFT_CHECKOUT", file=sys.stderr)
        return 2
    repo = sys.argv[1]
    names: dict[str, set[str]] = collections.defaultdict(set)
    for pr, (commit, files) in IMPORTERS.items():
        for path in files:
            for m in LITERAL.finditer(source(repo, commit, path)):
                name = m.group(1)
                if name[0].isupper() or "." in name:
                    names[name].add(pr)
    prs = list(IMPORTERS)
    print("# Names each importer reads\n")
    print("Generated by `tools/format/inventory.py` from string literals in each importer's non-test")
    print("source. A name listed here is referenced in code; it says nothing about how it is used.\n")
    print("| Importer | Commit |\n|---|---|")
    for pr, (commit, _) in IMPORTERS.items():
        print(f"| #{pr} | `{commit[:12]}` |")
    print()
    print("| Name | " + " | ".join(f"#{p}" for p in prs) + " |")
    print("|---|" + "---|" * len(prs))
    for name, readers in sorted(names.items(), key=lambda kv: (-len(kv[1]), kv[0].lower())):
        cells = " | ".join("x" if p in readers else "" for p in prs)
        print(f"| `{name}` | {cells} |")
    return 0


if __name__ == "__main__":
    sys.exit(main())
